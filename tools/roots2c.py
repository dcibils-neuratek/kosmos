"""
Mozilla's roots as a C array, for curl in JetSki's network process
(`docs/w7.md` W7b).

`assets/ca/cacert.pem` is the one list of authorities Kosmos trusts: the
TLS Kit's anchors are made from it at build time (`tls_anchors.c`), and
this makes the same file the bytes curl is handed (`CURLOPT_CAINFO_BLOB`,
in `CurlSSLHandleKosmos.cpp`). Two forms of one list, so a root added or
withdrawn upstream is added or withdrawn for both.

The length is a symbol beside the bytes, and the bytes end in a NUL that
the length does not count, so they are also a C string.

Usage: roots2c.py cacert.pem out.c
"""

import sys


def main():
    source, out = sys.argv[1], sys.argv[2]
    with open(source, "rb") as f:
        data = f.read()
    if b"-----BEGIN CERTIFICATE-----" not in data:
        sys.exit("roots2c: %s holds no certificate" % source)
    lines = ["/* Generated by tools/roots2c.py from %s - Mozilla's roots, MPL 2.0. */" % source,
             "const unsigned long kosmos_ca_roots_size = %d;" % len(data),
             "const unsigned char kosmos_ca_roots[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("%d" % b for b in data[i:i + 16]) + ",")
    lines.append("    0\n};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
