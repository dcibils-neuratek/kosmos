"""The EGL Kit's GL ES functions (`user/kits/egl/`, `docs/w6.md` W6b).

Writes a C file with one definition for every GL ES 3.2 function the
Khronos header declares, each stopping the process with its own name:
the EGL Kit has no display, so no context, so a call to one is a caller
that did not ask EGL first - a bug to see, not an answer to invent.

Usage: gles_unreached.py GLES3/gl32.h OUT.c [DEFINED.txt]

DEFINED.txt names, one a line, functions something else in the image
already defines - TinyGL's GL 1.1, whose names GL ES shares - and those
are left to it rather than defined twice.

Generated from the header rather than written, so that the stubs are
exactly the functions and the signatures the header has, and a header
WebKit updates brings its new functions with it.
"""

import re
import sys

PROTOTYPE = re.compile(r"^GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*)\);\s*$")


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    header, out = sys.argv[1], sys.argv[2]
    taken = set()
    if len(sys.argv) == 4:
        taken = {line.strip() for line in open(sys.argv[3]) if line.strip()}
    found, left = [], []
    for line in open(header):
        m = PROTOTYPE.match(line.strip())
        if m:
            (left if m.group(2) in taken else found).append(m.groups())
    if len(found) + len(left) < 300:
        sys.exit("gles_unreached: %d functions in %s - not GL ES 3.2's"
                 % (len(found) + len(left), header))

    with open(out, "w") as f:
        f.write("/* Kosmos. Copyright (c) 2026 Diego Cibils. MIT; see LICENSE. */\n")
        f.write("/* Generated by tools/gles_unreached.py from %s: %d functions. */\n"
                % (header.split("include/")[-1], len(found)))
        if left:
            f.write("/* Left to what already defines them: %s. */\n"
                    % ", ".join(name for _, name, _ in left))
        f.write("\n")
        f.write("#include <GLES3/gl32.h>\n#include <assert.h>\n\n")
        f.write("/* The header names every parameter, and no stub reads one. */\n"
                "#pragma GCC diagnostic ignored \"-Wunused-parameter\"\n\n")
        f.write("__attribute__((noreturn, cold)) static void unreached(const char *name)\n{\n"
                "    /* panic() prints its message and ends the process. */\n"
                "    char said[96] = \"GL ES with no display: \";\n"
                "    unsigned at = 23, i = 0;\n"
                "    while (name[i] && at < sizeof said - 1)\n"
                "        said[at++] = name[i++];\n"
                "    said[at] = 0;\n"
                "    panic(said);\n}\n\n")
        for ret, name, args in found:
            f.write("%s GL_APIENTRY %s(%s)\n{\n    unreached(\"%s\");\n}\n\n"
                    % (ret, name, args, name))
    print("gles_unreached: %d functions, %d left to what defines them"
          % (len(found), len(left)))


if __name__ == "__main__":
    main()
