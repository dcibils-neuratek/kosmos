/*
 * A monitor's EDID, decoded (`edid.h` says what and where each rule comes
 * from). Only whole blocks are read: the length decides how many
 * extensions there are, and nothing inside a block reaches past its 128
 * bytes.
 */

#include "edid.h"

/* The base block (`struct edid` in `drm_edid.h`). */
#define B_MFG           8
#define B_PRODUCT       10
#define B_SERIAL        12
#define B_WEEK          16
#define B_YEAR          17
#define B_VERSION       18
#define B_REVISION      19
#define B_INPUT         20
#define B_WIDTH_CM      21
#define B_HEIGHT_CM     22
#define B_FEATURES      24
#define B_ESTABLISHED   35
#define B_STANDARD      38
#define B_DESCRIPTORS   54
#define B_EXTENSIONS    126
#define DESCRIPTOR      18u

#define INPUT_DIGITAL           0x80u   /* DRM_EDID_INPUT_DIGITAL */
#define FEATURE_PREFERRED       0x02u   /* DRM_EDID_FEATURE_PREFERRED_TIMING */

/* Display descriptor tags (`EDID_DETAIL_*`). */
#define TAG_SERIAL      0xFFu
#define TAG_RANGE       0xFDu
#define TAG_NAME        0xFCu
#define TAG_STANDARD    0xFAu
#define TAG_EST3        0xF7u

/* The range descriptor's kinds (`DRM_EDID_*_FLAG`), and its 1.4 offsets. */
#define RANGE_GTF       0x00u
#define RANGE_GTF2      0x02u
#define RANGE_CVT       0x04u
#define CVT_RB          0x10u           /* DRM_EDID_CVT_FLAGS_REDUCED_BLANKING */

/* A detailed timing's misc byte (`DRM_EDID_PT_*`). */
#define PT_HSYNC_POS    0x02u
#define PT_VSYNC_POS    0x04u
#define PT_STEREO       0x20u
#define PT_INTERLACED   0x80u

/* Extensions (`drm_edid.h`). */
#define CEA_EXT         0x02u
#define DISPLAYID_EXT   0x70u

/* CTA data block tags (`CTA_DB_*`) and the vendors' OUIs. */
#define CTA_DB_VIDEO    2u
#define CTA_DB_VENDOR   3u
#define HDMI_OUI        0x000C03u       /* HDMI_IEEE_OUI */
#define HDMI_FORUM_OUI  0xC45DD8u       /* HDMI_FORUM_IEEE_OUI */

/* DisplayID data blocks (`drm_displayid_internal.h`). */
#define DID_TYPE_1      0x03u           /* DATA_BLOCK_TYPE_1_DETAILED_TIMING */
#define DID_TYPE_7      0x22u           /* DATA_BLOCK_2_TYPE_7_DETAILED_TIMING */
#define DID_TIMING      20u             /* struct displayid_detailed_timings_1 */

/* The mode tables, as `drm_edid.c` keeps them: the clock in kHz, then
 * DRM_MODE's horizontal and vertical numbers without the skew and scan. */
#define T_I     0x01u                   /* DRM_MODE_FLAG_INTERLACE */
#define T_PH    0x02u                   /* DRM_MODE_FLAG_PHSYNC */
#define T_PV    0x04u                   /* DRM_MODE_FLAG_PVSYNC */
#define T_DC    0x08u                   /* DRM_MODE_FLAG_DBLCLK */

struct timing {
    uint32_t clock;
    uint16_t h, hss, hse, ht;
    uint16_t v, vss, vse, vt;
    uint8_t  flags;
};

/* Established timings III: width, height, refresh, reduced blanking. */
struct est3 {
    uint16_t w, h;
    uint8_t  r, rb;
};

